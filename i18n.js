// 現在の言語（ja がデフォルト）。m キー（j/e/k）への対応も持つ。
function twGetLang(){ return localStorage.getItem("stw-lang") || "ja"; }
function twMKey(){ return {ja:"j",en:"e",ko:"k"}[twGetLang()]; }
function twT(key){ const L = I18N[twGetLang()] || I18N.ja; return L[key] ?? I18N.ja[key] ?? key; }
function twApplyI18n(root){
  (root||document).querySelectorAll("[data-i18n]").forEach(el=>{ el.textContent = twT(el.dataset.i18n); });
  (root||document).querySelectorAll("[data-i18n-html]").forEach(el=>{ el.innerHTML = twT(el.dataset.i18nHtml); }); // <em>/<strong> を含む文用
  (root||document).querySelectorAll("[data-i18n-ph]").forEach(el=>{ el.placeholder = twT(el.dataset.i18nPh); });
}
function twCycleLang(){
  const order = ["ja","en","ko"];
  const next = order[(order.indexOf(twGetLang())+1)%order.length];
  localStorage.setItem("stw-lang", next);
  document.documentElement.lang = {ja:"ja",en:"en",ko:"ko"}[next];
  const btn = document.getElementById("langBtn");
  if (btn) btn.textContent = {ja:"日",en:"EN",ko:"한"}[next];
  twApplyI18n();
  if (typeof onLangChange === "function") onLangChange();
}
